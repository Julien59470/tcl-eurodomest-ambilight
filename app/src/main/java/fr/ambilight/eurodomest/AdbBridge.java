package fr.ambilight.eurodomest;

import android.content.Context;
import android.os.Build;
import android.security.keystore.KeyGenParameterSpec;
import android.security.keystore.KeyProperties;
import java.math.BigInteger;
import java.security.KeyPairGenerator;
import java.security.KeyStore;
import java.security.PrivateKey;
import java.security.cert.Certificate;
import java.util.Calendar;
import java.util.Date;
import java.util.concurrent.TimeUnit;
import javax.security.auth.x500.X500Principal;
import java.io.ByteArrayOutputStream;
import java.io.InputStream;
import io.github.muntashirakon.adb.AbsAdbConnectionManager;
import io.github.muntashirakon.adb.AdbStream;

/**
 * Local Android 14 ADB/TLS, without legacy tcpip:5555 and without a root daemon.
 * Certificate/private key generated by Android Keystore and never exported.
 * ADB is used only after the user has explicitly enabled wireless debugging
 * and accepted the pairing code in Android settings.
 */
public final class AdbBridge extends AbsAdbConnectionManager {
    private static final String ALIAS="eurodomest_adb_pair_v07";
    private static volatile AdbBridge singleton;
    private final PrivateKey privateKey;
    private final Certificate certificate;
    private volatile AdbStream activeCapture;

    private AdbBridge() throws Exception {
        setApi(Build.VERSION.SDK_INT);
        setTimeout(5,TimeUnit.SECONDS);
        KeyStore store=KeyStore.getInstance("AndroidKeyStore");
        store.load(null);
        if(!store.containsAlias(ALIAS)){
            Calendar expiry=Calendar.getInstance();
            expiry.add(Calendar.YEAR,10);
            KeyPairGenerator gen=KeyPairGenerator.getInstance("RSA","AndroidKeyStore");
            gen.initialize(new KeyGenParameterSpec.Builder(ALIAS,
                KeyProperties.PURPOSE_SIGN|KeyProperties.PURPOSE_VERIFY)
                .setKeySize(2048)
                .setDigests(KeyProperties.DIGEST_SHA256,KeyProperties.DIGEST_SHA512)
                .setSignaturePaddings(KeyProperties.SIGNATURE_PADDING_RSA_PKCS1)
                .setCertificateSubject(new X500Principal("CN=Ambilight TCL ADB"))
                .setCertificateSerialNumber(BigInteger.valueOf(7947))
                .setCertificateNotBefore(new Date(System.currentTimeMillis()-86400000))
                .setCertificateNotAfter(expiry.getTime()).build());
            gen.generateKeyPair();
        }
        privateKey=(PrivateKey)store.getKey(ALIAS,null);
        certificate=store.getCertificate(ALIAS);
        if(privateKey==null||certificate==null)throw new IllegalStateException("Identité ADB inaccessible");
    }
    public static synchronized AdbBridge get() throws Exception {
        if(singleton==null)singleton=new AdbBridge();
        return singleton;
    }
    @Override protected PrivateKey getPrivateKey(){return privateKey;}
    @Override protected Certificate getCertificate(){return certificate;}
    @Override protected String getDeviceName(){return "TCL-Eurodomest-Ambilight";}

    public synchronized boolean pairLocal(int port,String code) throws Exception {
        if(port<1024||port>65535||code==null||!code.matches("[0-9]{6}"))
            throw new IllegalArgumentException("Port ou code d'association invalide");
        return pair("127.0.0.1",port,code);
    }

    public synchronized boolean connectLocal(Context context) throws Exception {
        if(isConnected())return true;
        try{disconnect();}catch(Exception ignored){}
        // mDNS resolves the dynamic TLS port. We do not expose legacy ADB over Wi-Fi.
        boolean found=connectTls(context.getApplicationContext(),7000);
        return found||isConnected();
    }
    /**
     * One complete PNG from the ADB shell. This is NOT a zero-copy capture:
     * the 4K screenshot is composed and compressed by Android before sampling.
     */
    public byte[] screenshotPng() throws Exception {
        AdbStream stream;
        synchronized(this){
            if(!isConnected())throw new IllegalStateException("ADB non connecté");
            stream=openStream("exec:screencap -p");
            activeCapture=stream;
        }
        try(AdbStream work=stream;InputStream in=stream.openInputStream();
            ByteArrayOutputStream bytes=new ByteArrayOutputStream(262144)){
            byte[] buf=new byte[16384];
            int count;
            while((count=in.read(buf))!=-1){
                if(Thread.currentThread().isInterrupted())throw new InterruptedException("Capture interrompue");
                if(bytes.size()+count>24*1024*1024)throw new IllegalStateException("Capture PNG trop volumineuse");
                bytes.write(buf,0,count);
            }
            byte[] out=bytes.toByteArray();
            if(out.length<16||out[0]!=(byte)0x89||out[1]!='P'||out[2]!='N'||out[3]!='G')
                throw new IllegalStateException("ADB n'a pas fourni de PNG valide");
            return out;
        }finally{activeCapture=null;}
    }
    public void cancelCapture(){
        AdbStream stream=activeCapture;
        if(stream!=null)try{stream.close();}catch(Exception ignored){}
    }
    public synchronized void disconnectSafely(){
        cancelCapture();
        try{disconnect();}catch(Exception ignored){}
    }
}
